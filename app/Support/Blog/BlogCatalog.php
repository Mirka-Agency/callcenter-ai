    /**
     * @return list<array{slug: ?string, label: string, icon: string, count: int}>
     */
    public static function filters(): array
    {
        $counts = self::counts();
        $filters = [[
            'slug' => null,
            'label' => 'همه مطالب',
            'icon' => 'grid',
            'count' => array_sum($counts),
        ]];

        foreach (self::categories() as $category) {
            $filters[] = [
                'slug' => $category['slug'],
                'label' => $category['label'],
                'icon' => $category['icon'],
                'count' => $counts[$category['slug']] ?? 0,
            ];
        }

        return $filters;
    }

    /**
     * @return array<string, int>
     */
    public static function counts(): array
    {
        return self::entries()
            ->countBy('category')
            ->all();
    }

    public static function find(string $slug): ?array
    {
        $post = self::entries()->firstWhere('slug', $slug);

        return is_array($post) ? self::present($post) : null;
    }

    /**
     * @return list<array<string, mixed>>
     */
    public static function related(string $slug, int $limit = 3): array
    {
        $current = self::entries()->firstWhere('slug', $slug);

        if (! is_array($current)) {
            return [];
        }

        $others = self::entries()->reject(fn (array $post): bool => $post['slug'] === $slug);
        $same = $others->where('category', $current['category']);
        $rest = $others->reject(fn (array $post): bool => $post['category'] === $current['category']);

        return $same
            ->concat($rest)
            ->take($limit)
            ->map(fn (array $post): array => self::present($post))
            ->values()
            ->all();
    }

    public static function paginate(?string $category, ?string $query, int $page): LengthAwarePaginator
    {
        $posts = self::filtered($category, $query);
        $page = max(1, $page);
        $slice = $posts->slice(($page - 1) * self::PER_PAGE, self::PER_PAGE)->values();

        return new LengthAwarePaginator(
            $slice->map(fn (array $post): array => self::present($post))->all(),
            $posts->count(),
            self::PER_PAGE,
            $page,
            [
                'path' => route('blog'),
                'query' => array_filter([
                    'category' => $category,
                    'q' => $query,
                ]),
            ],
        );
    }

    public static function category(?string $slug): ?string
    {
        if ($slug === null || $slug === '') {
            return null;
        }

        return in_array($slug, array_column(self::categories(), 'slug'), true) ? $slug : null;
    }

    /**
     * Static marketing catalog used to seed the database-backed blog.
     *
     * @return array{categories: list<array{slug: string, label: string, icon: string}>, posts: list<array<string, mixed>>}
     */
    public static function seedData(): array
    {
        return [
            'categories' => self::categories(),
            'posts' => self::posts(),
        ];
    }

    /**
     * @return Collection<int, array<string, mixed>>
     */
    private static function filtered(?string $category, ?string $query): Collection
    {
        $needle = self::normalize($query ?? '');

        return self::entries()
            ->when($category, fn (Collection $posts): Collection => $posts->where('category', $category)->values())
            ->when($needle !== '', function (Collection $posts) use ($needle): Collection {
                return $posts
                    ->filter(function (array $post) use ($needle): bool {
                        $haystack = self::normalize($post['title'].' '.$post['excerpt']);

                        return str_contains($haystack, $needle);
                    })
                    ->values();
            });
    }

    /**
     * @param  array<string, mixed>  $post
     * @return array<string, mixed>
     */
    private static function present(array $post): array
    {
        $category = collect(self::categories())->firstWhere('slug', $post['category']);

        $post['category_label'] = $category['label'] ?? '';
        $post['category_icon'] = $category['icon'] ?? 'doc';
        $post['tone'] = (abs(crc32((string) $post['slug'])) % 3) + 1;

        return $post;
    }

    private static function normalize(string $value): string
    {
        $value = mb_strtolower(trim($value));
        $value = str_replace(['ي', 'ك', '‌'], ['ی', 'ک', ' '], $value);

        return preg_replace('/\s+/u', ' ', $value) ?? $value;
    }

    /**
     * @return Collection<int, array<string, mixed>>
     */
    private static function entries(): Collection
    {
        return collect(self::posts())
            ->sortByDesc('published_on_sort')
            ->values();
    }

